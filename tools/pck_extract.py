#!/usr/bin/env python3
"""Writes SolarSystem/IauRotation.hpp from the NAIF text kernel pck00011.tpc
(https://naif.jpl.nasa.gov/pub/naif/generic_kernels/pck/pck00011.tpc), the
IAU WGCCRE 2015 rotation models and triaxial radii.
Usage: pck_extract.py pck00011.tpc SolarSystem/IauRotation.hpp"""
import re, sys

BODIES = [('Sun', 10), ('Mercury', 199), ('Venus', 299), ('Earth', 399), ('Mars', 499), ('Phobos', 401),
          ('Deimos', 402), ('Jupiter', 599), ('Io', 501), ('Europa', 502), ('Ganymede', 503),
          ('Callisto', 504), ('Saturn', 699), ('Mimas', 601), ('Enceladus', 602), ('Dione', 604),
          ('Rhea', 605), ('Titan', 606), ('Iapetus', 608), ('Uranus', 799), ('Miranda', 705),
          ('Ariel', 701), ('Umbriel', 702), ('Titania', 703), ('Oberon', 704), ('Neptune', 899),
          ('Triton', 801), ('Pluto', 999), ('Charon', 901), ('Ceres', 2000001), ('Pallas', 2000002),
          ('Vesta', 2000004), ('Eros', 2000433), ('Ida', 2431010), ('Gaspra', 9511010)]

def parse(path):
    kv = {}
    for block in re.findall(r'\\begindata(.*?)\\begintext', open(path).read(), re.S):
        for m in re.finditer(r'(\w+)\s*=\s*\(([^)]*)\)|(\w+)\s*=\s*([^\s(][^\n]*)', block):
            key, raw = (m.group(1), m.group(2)) if m.group(1) else (m.group(3), m.group(4))
            kv[key] = [float(x.replace('D', 'E')) for x in raw.replace(',', ' ').split()]
    return kv

def main(src, out):
    kv = parse(src)
    rows = []
    for name, code in BODIES:
        get = lambda k, n=3: (kv.get('BODY%d_%s' % (code, k), []) + [0.0] * n)[:n]
        radii = get('RADII')
        terms = []
        system = code // 100 if code < 1000 else None
        angles = kv.get('BODY%d_NUT_PREC_ANGLES' % system, []) if system else []
        width = int(kv.get('BODY%d_MAX_PHASE_DEGREE' % system, [1])[0]) + 1 if system else 2
        ra, dec, pm = (kv.get('BODY%d_NUT_PREC_%s' % (code, k), []) for k in ('RA', 'DEC', 'PM'))
        for i in range(max(len(ra), len(dec), len(pm))):
            a, d, w = ((s[i] if i < len(s) else 0.0) for s in (ra, dec, pm))
            if a or d or w:
                ang = (angles[i * width:(i + 1) * width] + [0.0, 0.0, 0.0])[:3]
                terms.append('{%r, %r, %r, %r, %r, %r}' % (*ang, a, d, w))
        rows.append('        {"%s", {%r, %r, %r}, {%s}, {%s}, {%s}, {%s}}' % (
            name, *radii, ', '.join(map(repr, get('POLE_RA'))), ', '.join(map(repr, get('POLE_DEC'))),
            ', '.join(map(repr, get('PM'))), ', '.join(terms)))
    with open(out, 'w') as f:
        f.write('''#pragma once
#include <vector>

// GENERATED by tools/pck_extract.py from NAIF pck00011.tpc (IAU WGCCRE 2015). Do not edit.
namespace Astro {

    // One periodic term: argument = a0 + a1*T + a2*T^2 (deg, T in Julian centuries TDB),
    // adding ra*sin to the pole RA, dec*cos to the pole Dec and pm*sin to W (deg).
    struct IauTerm { double a0, a1, a2, ra, dec, pm; };

    // Pole RA/Dec: c0 + c1*T + c2*T^2 (deg). Prime meridian W: c0 + c1*d + c2*d^2 (deg, d in days TDB).
    // Radii in km along the body-fixed x, y, z axes; zero when the kernel has none.
    struct IauBody {
        const char* name;
        double radii[3];
        double ra[3], dec[3], pm[3];
        std::vector<IauTerm> terms;
    };

    inline const std::vector<IauBody>& iauBodies() {
        static const std::vector<IauBody> table = {
%s
        };
        return table;
    }
}
''' % ',\n'.join(rows))

if __name__ == '__main__':
    main(*sys.argv[1:3])
